from __future__ import annotations

import os
from pathlib import Path

import pytest

from backend.core.config import Settings
from backend.ingestion.filters import SkipReason, classify_content, classify_dir, classify_file
from backend.ingestion.limits import IngestLimits, LimitTracker
from backend.ingestion.walk import walk_tree

MAX = 1024


def _no_children(_: str) -> bool:
    return False


@pytest.mark.parametrize(
    ("name", "reason"),
    [
        (".git", SkipReason.VCS),
        (".hg", SkipReason.VCS),
        (".venv", SkipReason.VIRTUALENV),
        ("venv", SkipReason.VIRTUALENV),
        ("site-packages", SkipReason.VIRTUALENV),
        ("node_modules", SkipReason.NODE_MODULES),
        ("__pycache__", SkipReason.CACHE),
        (".tox", SkipReason.CACHE),
        (".nox", SkipReason.CACHE),
        (".mypy_cache", SkipReason.CACHE),
        (".pytest_cache", SkipReason.CACHE),
        (".ruff_cache", SkipReason.CACHE),
        ("build", SkipReason.BUILD_OUTPUT),
        ("dist", SkipReason.BUILD_OUTPUT),
        (".eggs", SkipReason.BUILD_OUTPUT),
        ("mypkg.egg-info", SkipReason.BUILD_OUTPUT),
        (".next", SkipReason.BUILD_OUTPUT),
        (".nuxt", SkipReason.BUILD_OUTPUT),
        ("coverage", SkipReason.COVERAGE),
        ("htmlcov", SkipReason.COVERAGE),
    ],
)
def test_pruned_directories(name: str, reason: SkipReason) -> None:
    assert classify_dir(name, _no_children) == reason


@pytest.mark.parametrize("name", ["app", "src", "migrations", "env", "tests", "versions"])
def test_regular_directories_are_kept(name: str) -> None:
    assert classify_dir(name, _no_children) is None


def test_virtualenv_detected_by_pyvenv_cfg() -> None:
    assert classify_dir("env", lambda n: n == "pyvenv.cfg") == SkipReason.VIRTUALENV
    assert classify_dir("anything", lambda n: n == "pyvenv.cfg") == SkipReason.VIRTUALENV


def test_build_package_with_init_is_source() -> None:
    assert classify_dir("build", lambda n: n == "__init__.py") is None


def test_nested_repository_is_pruned() -> None:
    assert classify_dir("vendor_repo", lambda n: n == ".git") == SkipReason.NESTED_REPOSITORY


@pytest.mark.parametrize(
    ("path", "reason"),
    [
        (".env", SkipReason.SENSITIVE),
        ("backend/.env.production", SkipReason.SENSITIVE),
        ("certs/server.pem", SkipReason.SENSITIVE),
        ("deploy/id_rsa", SkipReason.SENSITIVE),
        ("config/secrets.yaml", SkipReason.SENSITIVE),
        ("logo.PNG", SkipReason.BINARY),
        ("lib/native.so", SkipReason.BINARY),
        ("model.pkl", SkipReason.BINARY),
        (".DS_Store", SkipReason.BINARY),
        ("api/service_pb2.py", SkipReason.GENERATED),
        ("api/service_pb2_grpc.py", SkipReason.GENERATED),
        ("static/app.min.js", SkipReason.MINIFIED),
        ("static/site.min.css", SkipReason.MINIFIED),
    ],
)
def test_file_name_classification(path: str, reason: SkipReason) -> None:
    assert classify_file(path, 10, MAX) == reason


def test_oversized_and_normal_files() -> None:
    assert classify_file("app/big.py", MAX + 1, MAX) == SkipReason.OVERSIZED
    assert classify_file("app/ok.py", MAX, MAX) is None
    assert classify_file("README.md", 10, MAX) is None


def test_sensitive_wins_over_size() -> None:
    assert classify_file(".env", MAX * 10, MAX) == SkipReason.SENSITIVE


def test_content_classification() -> None:
    assert classify_content("x.txt", b"abc\x00def") == SkipReason.BINARY
    assert classify_content("x.py", b"# Code generated by protoc. DO NOT EDIT.\n") == (
        SkipReason.GENERATED
    )
    assert classify_content("x.py", b'"""Module."""\n# @generated\n') == SkipReason.GENERATED
    assert classify_content("a.js", b"var a=" + b"1+" * 1000 + b"1;") == SkipReason.MINIFIED
    assert classify_content("a.js", b"const a = 1;\n" * 200) is None
    assert classify_content("x.py", b"import os\n\nprint('hello')\n") is None


def test_marker_after_header_is_not_generated() -> None:
    body = b"import os\n" * 10 + b"# this table was generated by hand\n"
    assert classify_content("x.py", body) is None


def test_django_and_alembic_migrations_are_kept() -> None:
    django = b"# Generated by Django 4.2 on 2024-01-01 10:00\nfrom django.db import migrations\n"
    assert classify_content("shop/migrations/0001_initial.py", django) is None
    alembic = b'"""add table\n\nRevision ID: abc\n"""\n# auto-generated by Alembic\n'
    assert classify_content("alembic/versions/abc_add.py", alembic) is None


def _limits(**overrides: int) -> IngestLimits:
    base = {
        "max_repo_files": 100,
        "max_repo_bytes": 10_000,
        "max_file_bytes": 1_000,
        "max_python_files": 10,
    }
    base.update(overrides)
    return IngestLimits(**base)


def test_tracker_file_limit_stops_and_records_once() -> None:
    tracker = LimitTracker(_limits(max_repo_files=2))
    assert tracker.admit(1, kept=True)
    assert tracker.admit(1, kept=False)
    assert not tracker.admit(1, kept=True)
    assert not tracker.admit(1, kept=True)
    assert tracker.stopped
    assert len(tracker.hit) == 1
    assert tracker.hit[0].startswith("max_repo_files (2)")


def test_tracker_byte_limit_counts_only_kept_bytes() -> None:
    tracker = LimitTracker(_limits(max_repo_bytes=10))
    assert tracker.admit(500, kept=False)
    assert tracker.admit(10, kept=True)
    assert not tracker.admit(1, kept=True)
    assert tracker.hit[0].startswith("max_repo_bytes")


def test_tracker_python_limit_does_not_stop() -> None:
    tracker = LimitTracker(_limits(max_python_files=1))
    assert tracker.admit_python()
    assert not tracker.admit_python()
    assert not tracker.stopped
    assert tracker.hit[0].startswith("max_python_files")


def _write(root: Path, files: dict[str, bytes]) -> None:
    for rel, data in files.items():
        path = root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)


def test_walk_prunes_without_descending_and_is_sorted(tmp_path: Path) -> None:
    _write(
        tmp_path,
        {
            "b.py": b"",
            "a.py": b"",
            "pkg/z.py": b"",
            "node_modules/x/y.js": b"",
            "pkg/__pycache__/z.pyc": b"",
        },
    )
    entries = list(walk_tree(tmp_path, LimitTracker(_limits())))
    paths = [e.rel_path for e in entries]
    assert paths == ["a.py", "b.py", "node_modules/", "pkg/__pycache__/", "pkg/z.py"]
    pruned = {e.rel_path: e.skip_reason for e in entries if e.is_dir}
    assert pruned == {
        "node_modules/": SkipReason.NODE_MODULES,
        "pkg/__pycache__/": SkipReason.CACHE,
    }


def test_walk_never_follows_symlinks(tmp_path: Path) -> None:
    outside = tmp_path / "outside"
    _write(outside, {"secret.py": b"x = 1"})
    root = tmp_path / "root"
    _write(root, {"main.py": b""})
    os.symlink(outside, root / "linked_dir")
    os.symlink(outside / "secret.py", root / "linked_file.py")
    entries = {e.rel_path: e for e in walk_tree(root, LimitTracker(_limits()))}
    assert entries["linked_dir"].skip_reason == SkipReason.SYMLINK
    assert entries["linked_file.py"].skip_reason == SkipReason.SYMLINK
    assert not any(p.startswith("linked_dir/") for p in entries)


def test_walk_records_special_files(tmp_path: Path) -> None:
    os.mkfifo(tmp_path / "pipe")
    entries = list(walk_tree(tmp_path, LimitTracker(_limits())))
    assert entries[0].rel_path == "pipe"
    assert entries[0].skip_reason == SkipReason.SPECIAL_FILE


def test_walk_stops_cleanly_at_file_limit(tmp_path: Path) -> None:
    _write(tmp_path, {f"f{i:02}.py": b"x" for i in range(10)})
    tracker = LimitTracker(_limits(max_repo_files=4))
    entries = list(walk_tree(tmp_path, tracker))
    assert len(entries) == 4
    assert tracker.stopped


def test_walk_excludes_perfpilot_data(tmp_path: Path) -> None:
    _write(tmp_path, {"data/workspaces/x/src/a.py": b"", "app.py": b""})
    entries = list(walk_tree(tmp_path, LimitTracker(_limits()), excluded_dirs=[tmp_path / "data"]))
    assert {e.rel_path: e.skip_reason for e in entries} == {
        "app.py": None,
        "data/": SkipReason.PERFPILOT_DATA,
    }


def test_limits_from_settings(tmp_path: Path) -> None:
    settings = Settings(data_dir=tmp_path, max_repo_files=7, max_python_files=3)
    limits = IngestLimits.from_settings(settings)
    assert limits.max_repo_files == 7
    assert limits.max_python_files == 3
