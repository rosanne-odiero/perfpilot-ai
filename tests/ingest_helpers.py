def write_tree(root: Path, files: dict[str, bytes]) -> Path:
    for rel, data in files.items():
        path = root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
    return root


def make_sample_repo(root: Path) -> Path:
    return write_tree(root, SAMPLE_FILES)


def zip_tree(source: Path, archive: Path, prefix: str = "") -> Path:
    """Zip every file under ``source`` (hidden files included) with an optional top-level dir."""
    with zipfile.ZipFile(archive, "w", zipfile.ZIP_DEFLATED) as zf:
        for dirpath, dirnames, filenames in os.walk(source):
            dirnames.sort()
            for name in sorted(filenames):
                path = Path(dirpath) / name
                rel = path.relative_to(source).as_posix()
                zf.write(path, f"{prefix}{rel}")
    return archive


def zip_entries(archive: Path, entries: dict[str, bytes]) -> Path:
    with zipfile.ZipFile(archive, "w", zipfile.ZIP_DEFLATED) as zf:
        for name, data in entries.items():
            zf.writestr(zipfile.ZipInfo(name), data)
    return archive
