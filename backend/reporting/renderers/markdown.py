"""GitHub-flavored Markdown renderer, suitable for pasting into a PR or issue.

Repository-derived text is escaped: HTML-significant characters become entities (GitHub renders
some raw HTML), inline-syntax characters (emphasis, links, code, tables, strikethrough) are
backslash-escaped, newlines are collapsed, and a leading block marker (heading, list, quote) is
neutralized. Code goes in fenced blocks whose fence is longer than any backtick run in it.
"""

from __future__ import annotations

import re
from collections.abc import Iterable

from backend.models.enums import Provenance, Severity
from backend.reporting.model import NOT_MEASURED_TEXT, SECTION_TITLES, AuditReport
from backend.reporting.renderers.common import format_datetime, humanize

_MD_SPECIAL = re.compile(r"([\\`*_\[\]|~])")
_BLOCK_START = re.compile(r"^(#|[-+=]|\d+[.)])")
_BACKTICKS = re.compile(r"`+")
_MERMAID_UNSAFE = re.compile(r"[^A-Za-z0-9_.]")


def md(text: object) -> str:
    """Escape repository-derived text for inline Markdown."""
    value = " ".join(str(text).split())
    value = _MD_SPECIAL.sub(r"\\\1", value)
    value = _BLOCK_START.sub(lambda m: m.group(1)[:-1] + "\\" + m.group(1)[-1], value)
    return value.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def code_span(text: object) -> str:
    value = " ".join(str(text).split()).replace("|", "\\|")
    longest = max((len(m) for m in _BACKTICKS.findall(value)), default=0)
    fence = "`" * (longest + 1)
    pad = " " if value.startswith("`") or value.endswith("`") else ""
    return f"{fence}{pad}{value}{pad}{fence}" if value else ""


def fenced(code: str, language: str = "") -> list[str]:
    longest = max((len(m) for m in _BACKTICKS.findall(code)), default=0)
    fence = "`" * max(3, longest + 1)
    return [f"{fence}{language}", code, fence]


def prov(p: Provenance | str) -> str:
    return f"**[{Provenance(p).value}]**"


def sev(s: Severity | str) -> str:
    return f"**{Severity(s).value}**"


def table(headers: list[str], rows: Iterable[list[str]]) -> list[str]:
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    out.extend("| " + " | ".join(cell or " " for cell in row) + " |" for row in rows)
    return out


def _heading(n: int) -> str:
    return f"## {n}. {SECTION_TITLES[n]}"


def _not_measured(explanation: str) -> list[str]:
    return [f"> **{NOT_MEASURED_TEXT}**", ">", f"> {explanation}"]


def _mermaid(report: AuditReport) -> list[str]:
    arch = report.architecture
    if not arch.key_edges:
        return []
    names = sorted({name for e in arch.key_edges for name in (e.source, e.target)})
    ids = {name: f"n{i}" for i, name in enumerate(names)}
    lines = ["```mermaid", "graph LR"]
    for name, node_id in ids.items():
        lines.append(f'  {node_id}["{_MERMAID_UNSAFE.sub("_", name)}"]')
    for i, edge in enumerate(arch.key_edges):
        lines.append(f"  {ids[edge.source]} --> {ids[edge.target]}")
        if edge.in_cycle:
            lines.append(f"  linkStyle {i} stroke:#b91c1c,stroke-width:2px")
    lines.append("```")
    return lines


def render_markdown(report: AuditReport) -> str:
    r = report
    out: list[str] = [
        f"# {md(r.metadata.title)}",
        "",
        f"Commit {code_span(r.repository.commit_sha or 'unknown')} · "
        f"{md(r.repository.mode)} audit · analyzed {format_datetime(r.repository.analyzed_at)} · "
        f"generated by {md(r.metadata.generator)}",
        "",
        "**Contents:** " + " · ".join(f"{n}. {title}" for n, title in SECTION_TITLES.items()),
        "",
        "### Provenance labels",
        "",
        *table(
            ["Label", "Meaning"],
            ([code_span(e.label.value), md(e.meaning)] for e in r.legend),
        ),
        "",
    ]

    # 1
    s = r.executive_summary
    out += [_heading(1), ""]
    for paragraph in s.text:
        out += [md(paragraph), ""]
    c = s.counts
    out += table(
        ["Files seen", "Python files analyzed", "Modules", "Findings", "Recommendations"],
        [
            [
                str(c.files_seen),
                str(c.python_files_analyzed),
                str(c.modules_indexed),
                str(c.findings_total),
                str(c.recommendations_total),
            ]
        ],
    )
    out += [
        "",
        "Severity: " + " · ".join(f"{sev(k)} {v}" for k, v in c.findings_by_severity.items()),
    ]
    out += ["", "**Top risks**", ""]
    if s.top_risks:
        out += table(
            ["Severity", "Finding", "Location", "Provenance"],
            (
                [sev(t.severity), md(t.title), code_span(t.location), prov(t.provenance)]
                for t in s.top_risks
            ),
        )
    else:
        out.append("No findings were reported.")
    out.append("")

    # 2
    repo = r.repository
    out += [_heading(2), ""]
    out += table(
        ["Field", "Value"],
        [
            ["Repository", md(repo.name)],
            ["Source", f"{md(humanize(repo.source_type))} · {code_span(repo.source_display)}"],
            ["Commit SHA", code_span(repo.commit_sha or "unknown")],
            ["Branch", md(repo.branch or "n/a")],
            ["Requested ref", md(repo.requested_ref or "default branch")],
            ["Analyzed at", format_datetime(repo.analyzed_at)],
            ["Mode / status", f"{repo.mode} / {repo.audit_status}"],
            ["PerfPilot version", md(repo.perfpilot_version)],
            ["Python (report environment)", md(f"{repo.python_version} on {repo.platform}")],
            ["LLM model used", md(repo.llm_model)],
        ],
    )
    out.append("")

    # 3
    f = r.files
    out += [_heading(3), ""]
    out += table(
        ["Files seen", "Python files analyzed", "Modules indexed", "Skipped", "Parse errors"],
        [
            [
                str(f.files_seen),
                str(f.python_files_analyzed),
                str(f.modules_indexed),
                str(f.skipped_total),
                str(len(f.parse_errors)),
            ]
        ],
    )
    out.append("")
    if f.languages:
        out.append("Languages: " + ", ".join(f"{md(k)} ({v})" for k, v in f.languages.items()))
        out.append("")
    if f.skipped_by_reason:
        out.append(
            "Skipped by reason: "
            + ", ".join(f"{md(k)} ({v})" for k, v in f.skipped_by_reason.items())
        )
        out.append("")
    out.append(
        "Limits reached: " + ("; ".join(md(x) for x in f.limits_hit) if f.limits_hit else "none")
    )
    out.append("")
    if f.parse_errors:
        out += table(
            ["File", "Parse error"],
            ([code_span(e.file_path), md(e.error)] for e in f.parse_errors),
        )
        out.append("")

    # 4
    a = r.architecture
    out += [
        _heading(4),
        "",
        f"{prov(a.provenance)} Built from import statements; no code executed.",
        "",
    ]
    if not a.index_available:
        out += ["No code index was stored for this audit.", ""]
    else:
        out.append(
            f"{a.node_count} modules, {a.edge_count} internal import edges, "
            f"{len(a.entrypoints)} entrypoints, {len(a.cycles)} import cycles, "
            f"{a.external_import_count} external packages."
        )
        if a.graph and a.graph.note:
            out.append(f"The graph image in the HTML/PDF report is capped: {md(a.graph.note)}.")
        out.append("")
        mermaid = _mermaid(r)
        if mermaid:
            out += [
                "Most depended-upon modules and entrypoints (import cycles in red):",
                "",
                *mermaid,
                "",
            ]
        if a.top_fan_in:
            out += table(
                ["Module", "Fan-in", "Fan-out", "Findings", "Flags"],
                (
                    [
                        code_span(m.module_name),
                        str(m.fan_in),
                        str(m.fan_out),
                        str(m.finding_count),
                        " ".join(
                            x
                            for x, on in (("entrypoint", m.is_entrypoint), ("cycle", m.in_cycle))
                            if on
                        ),
                    ]
                    for m in a.top_fan_in
                ),
            )
            out.append("")
        for cycle in a.cycles:
            out.append("- Cycle: " + code_span(" -> ".join([*cycle, cycle[0]])))
        if a.cycles:
            out.append("")
    if a.technologies:
        out += ["Technologies: " + ", ".join(md(t.name) for t in a.technologies), ""]
    for insight in a.insights:
        out += [f"- {prov(insight.provenance)} **{md(insight.title)}**: {md(insight.description)}"]
    if a.insights:
        out.append("")

    # 5
    out += [_heading(5), ""]
    if r.findings.entries:
        out += table(
            ["#", "Severity", "Finding", "Rule", "Location", "Confidence", "Provenance"],
            (
                [
                    str(e.rank),
                    sev(e.severity),
                    md(e.title),
                    code_span(e.rule_id),
                    code_span(e.location),
                    e.confidence.value,
                    prov(e.provenance),
                ]
                for e in r.findings.entries
            ),
        )
        out.append("")
        for e in r.findings.entries:
            out += [
                f"#### {e.rank}. {md(e.title)}",
                "",
                f"{sev(e.severity)} {prov(e.provenance)} · {code_span(e.location)} · "
                f"{md(humanize(e.category))} · confidence {e.confidence.value.lower()}",
                "",
                md(e.description),
                "",
                f"**Suggestion.** {md(e.suggestion)}",
            ]
            if e.tradeoffs:
                out += ["", f"**Trade-offs.** {md(e.tradeoffs)}"]
            if e.measured:
                m = e.measured
                out += [
                    "",
                    f"{prov(Provenance.MEASURED)} {code_span(m.function_name)}: "
                    f"{m.cumulative_time_ms:.2f} ms cumulative, {m.internal_time_ms:.2f} ms "
                    f"internal, {m.call_count} calls, {m.percentage_of_profiled_time:.1f}% of "
                    "profiled time.",
                ]
            out.append("")
    else:
        out += ["No findings were reported.", ""]

    # 6
    out += [_heading(6), ""]
    for ev in r.evidence.entries:
        link = f" · [view on GitHub]({ev.permalink})" if ev.permalink else ""
        out += [
            f"**{ev.rank}. {md(ev.title)}** {prov(ev.provenance)} · {code_span(ev.location)}{link}",
            "",
        ]
        if ev.withheld_reason:
            out += [md(ev.withheld_reason), ""]
        elif ev.lines:
            width = len(str(ev.lines[-1].number))
            body = "\n".join(f"{line.number:>{width}} | {line.text}" for line in ev.lines)
            out += [*fenced(body, "python"), ""]
    if not r.evidence.entries:
        out += ["No source references.", ""]

    # 7
    out += [_heading(7), ""]
    if r.runtime is None:
        out += _not_measured(
            "No repository code was executed for this audit, so there are no CPU or memory "
            "measurements. Runtime profiling requires an explicitly approved Runtime Audit."
        )
        out.append("")
    else:
        for p in r.runtime.profiles:
            out += [
                f"{prov(p.provenance)} Profile {code_span(p.profile_id)} ({md(p.profiler)}): "
                f"command {code_span(' '.join(p.command))}, wall time {p.wall_time_ms:.1f} ms"
                + (f", CPU {p.cpu_time_ms:.1f} ms" if p.cpu_time_ms is not None else "")
                + (f", peak RSS {p.peak_rss_mb:.1f} MB" if p.peak_rss_mb is not None else "")
                + ".",
                "",
            ]
            if p.hotspots:
                out += table(
                    ["Function", "Internal", "Cumulative", "Calls", "Share"],
                    (
                        [
                            code_span(h.function_name),
                            f"{h.internal_time_ms:.2f} ms",
                            f"{h.cumulative_time_ms:.2f} ms",
                            str(h.call_count),
                            f"{h.percentage_of_profiled_time:.1f}%",
                        ]
                        for h in p.hotspots
                    ),
                )
                out.append("")

    # 8
    out += [_heading(8), "", f"_{md(r.complexity.note)}_", ""]
    if r.complexity.entries:
        out += table(
            ["#", "Finding", "Location", "Estimate", "Provenance"],
            (
                [
                    str(x.rank),
                    md(x.title),
                    code_span(x.location),
                    "estimate: " + md(x.estimate),
                    prov(x.provenance),
                ]
                for x in r.complexity.entries
            ),
        )
    else:
        out.append("No complexity estimates were produced by the analysis.")
    out.append("")

    # 9
    out += [_heading(9), ""]
    for st in r.strategies.entries:
        out += [
            f"#### {st.rank}. {md(st.title)}",
            "",
            f"{prov(st.provenance)} · effort **{st.effort.value}** · "
            f"generated by {md(st.generated_by)}",
            "",
            md(st.summary),
            "",
            f"- **Strategy:** {md(st.proposed_strategy)}",
            f"- **Rationale:** {md(st.rationale)}",
            f"- **Expected effect (hypothesis):** {md(st.expected_effect)}",
            f"- **Uncertainty:** {md(st.uncertainty)}",
        ]
        if st.correctness_risks:
            out.append(f"- **Correctness risks:** {md(st.correctness_risks)}")
        if st.citations:
            out.append("- **Citations:** " + ", ".join(code_span(x) for x in st.citations))
        out.append("")
    if not r.strategies.entries:
        out += ["No recommendations were generated.", ""]

    # 10
    out += [_heading(10), "", md(r.code_changes.note), ""]
    for d in r.code_changes.entries:
        out += [f"**{md(d.title)}** {prov(d.provenance)}", ""]
        if d.withheld_reason:
            out += [md(d.withheld_reason), ""]
        elif d.diff:
            out += [*fenced(d.diff, "diff"), ""]

    # 11
    out += [_heading(11), ""]
    if r.validation is None:
        out += _not_measured("No candidate change was applied and validated for this audit.")
        out.append("")
    else:
        out += table(
            ["Validation", "Recommendation", "Status", "Command", "Provenance"],
            (
                [
                    code_span(o.validation_id),
                    code_span(o.recommendation_id or "n/a"),
                    f"**{o.status}**",
                    code_span(" ".join(o.command)),
                    prov(o.provenance),
                ]
                for o in r.validation.outcomes
            ),
        )
        out.append("")

    # 12
    out += [_heading(12), ""]
    if r.benchmarks is None:
        out += _not_measured("No A/B benchmark was run for this audit.")
        out.append("")
    else:
        rows = []
        for b in r.benchmarks.results:
            ci = (
                f"{b.speedup_ci_low:.2f} to {b.speedup_ci_high:.2f}x"
                if b.speedup_ci_low is not None and b.speedup_ci_high is not None
                else "n/a"
            )
            rows.append(
                [
                    md(b.name),
                    f"{b.baseline_median_ms:.2f} ms",
                    f"{b.candidate_median_ms:.2f} ms",
                    f"{b.speedup:.2f}x",
                    ci,
                    f"**{b.classification}**",
                    f"{b.sample_count} (+{b.warmup_runs} warmup)",
                    prov(b.provenance),
                ]
            )
        out += table(
            [
                "Benchmark",
                "Baseline median",
                "Candidate median",
                "Speedup",
                "CI",
                "Result",
                "Samples",
                "Provenance",
            ],
            rows,
        )
        out.append("")

    # 13
    out += [_heading(13), "", md(r.effort.note), ""]
    out += table(
        ["Size", "Meaning", "Recommendations"],
        ([f"**{k.value}**", md(v), str(r.effort.totals[k])] for k, v in r.effort.scale.items()),
    )
    out.append("")
    if r.effort.entries:
        out += table(
            ["Recommendation", "Effort", "Uncertainty", "Provenance"],
            (
                [md(e.title), e.effort.value, md(e.uncertainty), prov(e.provenance)]
                for e in r.effort.entries
            ),
        )
        out.append("")

    # 14
    out += [_heading(14), "", "Grouping rules:", ""]
    out += [f"- {md(rule)}" for rule in r.roadmap.rules]
    out.append("")
    for phase in r.roadmap.phases:
        out += [f"### {phase.name} ({len(phase.items)})", "", md(phase.description), ""]
        if phase.items:
            out += [
                f"- {md(i.title)} — {i.effort.value}, {md(i.reason)} {prov(i.provenance)}"
                for i in phase.items
            ]
        else:
            out.append("Nothing in this phase.")
        out.append("")

    # 15
    rp = r.limitations.reproducibility
    out += [_heading(15), "", "**Limitations**", ""]
    out += [f"- {md(item)}" for item in r.limitations.limitations]
    out += ["", "**Reproducibility**", ""]
    out += table(
        ["Setting", "Value"],
        [
            ["Commit SHA", code_span(rp.commit_sha or "unknown")],
            ["Source", code_span(rp.source_display)],
            ["PerfPilot version", md(rp.perfpilot_version)],
            *([md(k), code_span(v)] for k, v in rp.configuration.items()),
            *([md(k), code_span(v)] for k, v in rp.environment.items()),
        ],
    )
    out += ["", *fenced("\n".join(rp.commands), "bash"), ""]
    out += [
        "---",
        f"_Generated by {md(r.metadata.generator)} on {format_datetime(r.metadata.generated_at)} · "
        f"audit {code_span(r.metadata.audit_id)} · schema {r.schema_version} · "
        f"{r.metadata.redactions_applied} secret-like values redacted._",
        "",
    ]
    return "\n".join(out)
