"""Report provider for repository optimization candidates: sections 10, 11 and 12.

* Section 10 gets the real unified diff of every candidate (with its lifecycle state, who generated
  it, and its provenance: ``STATIC`` or ``AI_HYPOTHESIS`` until it is validated *and*
  benchmarked, then ``MEASURED``).
* Section 11 gets every finished sandbox validation (per-check outcomes, exact command).
* Section 12 gets every successful paired benchmark (medians, speedup, CI, classification and the
  raw per-run samples, which also feed the benchmark-samples CSV).

Audits without candidates get nothing from this provider, so static-only reports are unchanged.
"""

from __future__ import annotations

from typing import Any, get_args

from sqlalchemy import select
from sqlalchemy.orm import Session

from backend.models.enums import Provenance
from backend.models.orm.repo_optimization import (
    RepoBenchmarkRun,
    RepoOptimizationCandidate,
    RepoValidationRun,
)
from backend.optimization.repo_candidates import TIMED_DESCRIPTION, benchmark_samples
from backend.reporting.model import (
    BenchmarkClassification,
    BenchmarkResult,
    BenchmarkSample,
    DiffEntry,
    ValidationCheck,
    ValidationOutcome,
)
from backend.reporting.provider_registry import (
    ProviderContext,
    ProviderContribution,
    report_provider,
)
from backend.reporting.sources import SENSITIVE_WITHHELD, touches_sensitive_file, truncate_diff

MIB = 1024 * 1024
NS_PER_MS = 1_000_000
REPORTED_CHECK_STATUSES = {"PASSED", "FAILED", "INCONCLUSIVE", "NOT_RUN"}
CLASSIFICATIONS: dict[str, BenchmarkClassification] = {
    value: value for value in get_args(BenchmarkClassification)
}


def _label(candidate: RepoOptimizationCandidate) -> str:
    function = candidate.target_function or "module"
    return f"{function} ({candidate.target_file}) — candidate {candidate.id[:8]}"


def _flat(values: dict[str, Any]) -> dict[str, str]:
    flat: dict[str, str] = {}
    for key, value in values.items():
        if isinstance(value, dict):
            flat.update({f"{key}.{k}": str(v) for k, v in value.items() if v is not None})
        elif value is not None:
            flat[key] = str(value)
    return flat


def _diff_entry(candidate: RepoOptimizationCandidate) -> DiffEntry:
    title = (
        f"{_label(candidate)} for finding {candidate.rule_id} “{candidate.finding_title}”: "
        f"{candidate.state}, generated by {candidate.generated_by}, finding evidence "
        f"{candidate.evidence}, validation {candidate.validation_status}"
    )
    files = [candidate.target_file]
    if touches_sensitive_file(files):
        return DiffEntry(
            recommendation_id=candidate.finding_id,
            title=title,
            provenance=Provenance(candidate.provenance),
            files=files,
            diff=None,
            withheld_reason=SENSITIVE_WITHHELD,
        )
    diff, truncated = truncate_diff(candidate.proposed_diff)
    return DiffEntry(
        recommendation_id=candidate.finding_id,
        title=title,
        provenance=Provenance(candidate.provenance),
        files=files,
        diff=diff,
        truncated=truncated,
    )


def _validation(run: RepoValidationRun, finding_id: str) -> ValidationOutcome:
    checks = [
        ValidationCheck(
            name=str(check.get("name", "")),
            status=check["status"] if check.get("status") in REPORTED_CHECK_STATUSES else "NOT_RUN",
            detail=str(check.get("detail", "")),
        )
        for check in run.checks or []
        if isinstance(check, dict)
    ]
    return ValidationOutcome(
        validation_id=run.id,
        recommendation_id=finding_id,
        status=run.status if run.status in REPORTED_CHECK_STATUSES else "NOT_RUN",
        command=[str(a) for a in run.argv],
        checks=checks,
        environment=_flat(
            {
                **{k: v for k, v in (run.environment or {}).items() if k != "limits"},
                "limits": (run.environment or {}).get("limits") or run.limits,
                "summary": run.summary,
            }
        ),
    )


def _rss_mb(summary: dict[str, Any], variant: str) -> float | None:
    rss = (summary.get(variant) or {}).get("peak_rss_bytes") or {}
    median = rss.get("median")
    return float(median) / MIB if isinstance(median, int | float) else None


def _benchmark(
    session: Session, candidate: RepoOptimizationCandidate, run: RepoBenchmarkRun
) -> BenchmarkResult | None:
    summary = run.summary or {}
    base = ((summary.get("baseline") or {}).get("wall_ms") or {}).get("median")
    cand = ((summary.get("candidate") or {}).get("wall_ms") or {}).get("median")
    classification = CLASSIFICATIONS.get(run.classification or "")
    if run.speedup is None or classification is None or base is None or cand is None:
        return None
    samples = [
        BenchmarkSample(
            variant="baseline" if s.variant == "baseline" else "candidate",
            run_index=s.pair_index,
            wall_time_ms=s.wall_ns / NS_PER_MS,
            peak_memory_mb=s.peak_rss_bytes / MIB if s.peak_rss_bytes is not None else None,
        )
        for s in benchmark_samples(session, run.id)
        if not s.warmup and s.ok and s.wall_ns is not None
    ]
    return BenchmarkResult(
        benchmark_id=run.id,
        name=_label(candidate),
        recommendation_id=candidate.finding_id,
        baseline_median_ms=float(base),
        candidate_median_ms=float(cand),
        speedup=run.speedup,
        speedup_ci_low=run.speedup_ci_low,
        speedup_ci_high=run.speedup_ci_high,
        confidence_level=float((summary.get("ci") or {}).get("confidence", 0.95)),
        classification=classification,
        sample_count=run.runs,
        warmup_runs=run.warmups,
        baseline_peak_memory_mb=_rss_mb(summary, "baseline"),
        candidate_peak_memory_mb=_rss_mb(summary, "candidate"),
        environment=_flat(
            {
                "command": " ".join(str(a) for a in run.argv),
                **{k: v for k, v in (run.environment or {}).items() if k != "timed"},
                "seed": run.seed,
                "threshold_percent": run.threshold_percent,
                "classification_reason": run.classification_reason,
            }
        ),
        samples=samples,
        warnings=[
            f"Timed: {TIMED_DESCRIPTION}. Peak memory is getrusage ru_maxrss of the process "
            "(interpreter included).",
            *(str(w) for w in run.warnings or []),
        ],
    )


@report_provider("repo-optimization")
def repo_optimization(session: Session, ctx: ProviderContext) -> ProviderContribution | None:
    candidates = list(
        session.scalars(
            select(RepoOptimizationCandidate)
            .where(RepoOptimizationCandidate.audit_id == ctx.audit_id)
            .order_by(RepoOptimizationCandidate.created_at, RepoOptimizationCandidate.id)
        )
    )
    if not candidates:
        return None
    contribution = ProviderContribution()
    for candidate in candidates:
        if not candidate.proposed_diff:
            contribution.limitations.append(
                f"No patch candidate for finding {candidate.finding_id} ({candidate.rule_id} in "
                f"{candidate.target_file}): {candidate.error or 'no safe patch'}."
            )
            continue
        contribution.code_changes.append(_diff_entry(candidate))
        validations = session.scalars(
            select(RepoValidationRun)
            .where(RepoValidationRun.candidate_id == candidate.id)
            .order_by(RepoValidationRun.created_at)
        )
        for validation in validations:
            if validation.finished_at is None:
                continue
            contribution.validation_outcomes.append(_validation(validation, candidate.finding_id))
        benchmarks = session.scalars(
            select(RepoBenchmarkRun)
            .where(RepoBenchmarkRun.candidate_id == candidate.id)
            .order_by(RepoBenchmarkRun.created_at)
        )
        for run in benchmarks:
            if run.status == "SUCCEEDED" and (result := _benchmark(session, candidate, run)):
                contribution.benchmark_results.append(result)
            elif run.status == "FAILED":
                contribution.limitations.append(
                    f"Benchmark {run.id} of candidate {candidate.id[:8]} produced no comparison: "
                    f"{run.error or run.classification_reason or 'no reason recorded'}."
                )
    return contribution
