"""Path and content filters that decide which repository files are analyzed.

Every decision carries an explicit :class:`SkipReason` so the inventory can report *why* a file
was not analyzed. Directory filters are applied while walking (pruned directories are never
descended into), file-name filters run before a file is read or copied, and content filters run
on the bytes of files that passed the first two stages.
"""

from __future__ import annotations

from collections.abc import Callable
from enum import StrEnum
from pathlib import PurePosixPath

from backend.core.redaction import is_sensitive_path


class SkipReason(StrEnum):
    VCS = "vcs"
    NESTED_REPOSITORY = "nested_repository"
    VIRTUALENV = "virtualenv"
    NODE_MODULES = "node_modules"
    CACHE = "cache"
    BUILD_OUTPUT = "build_output"
    COVERAGE = "coverage"
    PERFPILOT_DATA = "perfpilot_data"
    OS_METADATA = "os_metadata"
    GENERATED = "generated"
    MINIFIED = "minified"
    BINARY = "binary"
    OVERSIZED = "oversized"
    SENSITIVE = "sensitive"
    SYMLINK = "symlink"
    SPECIAL_FILE = "special_file"
    UNREADABLE = "unreadable"
    PYTHON_FILE_LIMIT = "python_file_limit"


_DIR_NAMES: dict[str, SkipReason] = {
    ".git": SkipReason.VCS,
    ".hg": SkipReason.VCS,
    ".svn": SkipReason.VCS,
    ".bzr": SkipReason.VCS,
    ".venv": SkipReason.VIRTUALENV,
    "venv": SkipReason.VIRTUALENV,
    "site-packages": SkipReason.VIRTUALENV,
    "node_modules": SkipReason.NODE_MODULES,
    "bower_components": SkipReason.NODE_MODULES,
    "__pycache__": SkipReason.CACHE,
    ".tox": SkipReason.CACHE,
    ".nox": SkipReason.CACHE,
    ".mypy_cache": SkipReason.CACHE,
    ".pytest_cache": SkipReason.CACHE,
    ".ruff_cache": SkipReason.CACHE,
    ".hypothesis": SkipReason.CACHE,
    ".pytype": SkipReason.CACHE,
    ".parcel-cache": SkipReason.CACHE,
    ".turbo": SkipReason.CACHE,
    ".eggs": SkipReason.BUILD_OUTPUT,
    ".next": SkipReason.BUILD_OUTPUT,
    ".nuxt": SkipReason.BUILD_OUTPUT,
    ".svelte-kit": SkipReason.BUILD_OUTPUT,
    ".vercel": SkipReason.BUILD_OUTPUT,
    "coverage": SkipReason.COVERAGE,
    "htmlcov": SkipReason.COVERAGE,
    "__MACOSX": SkipReason.OS_METADATA,
}

# Pruned unless they look like a Python package (``build/__init__.py`` is source code).
_OUTPUT_DIR_NAMES = frozenset({"build", "dist"})

_BINARY_EXTENSIONS = frozenset(
    {
        # compiled / native
        ".pyc", ".pyo", ".pyd", ".so", ".dylib", ".dll", ".exe", ".o", ".a", ".lib", ".obj",
        ".class", ".jar", ".war", ".wasm", ".whl", ".egg",
        # archives
        ".zip", ".tar", ".gz", ".tgz", ".bz2", ".xz", ".7z", ".rar", ".zst",
        # images / media / fonts / documents
        ".png", ".jpg", ".jpeg", ".gif", ".bmp", ".ico", ".icns", ".webp", ".tif", ".tiff",
        ".psd", ".heic", ".avif", ".pdf", ".doc", ".docx", ".xls", ".xlsx", ".ppt", ".pptx",
        ".woff", ".woff2", ".ttf", ".otf", ".eot", ".mp3", ".mp4", ".m4a", ".wav", ".ogg",
        ".flac", ".mov", ".avi", ".mkv", ".webm",
        # data / model blobs
        ".sqlite", ".sqlite3", ".db", ".pkl", ".pickle", ".npy", ".npz", ".h5", ".hdf5",
        ".parquet", ".feather", ".arrow", ".onnx", ".pt", ".pth", ".ckpt", ".safetensors",
        ".bin", ".joblib",
    }
)  # fmt: skip

_BINARY_NAMES = frozenset({".DS_Store", ".coverage"})

_GENERATED_SUFFIXES = ("_pb2.py", "_pb2_grpc.py", "_pb2.pyi", ".pb.go", ".js.map", ".css.map")
_MINIFIED_SUFFIXES = (".min.js", ".min.mjs", ".min.css", "-min.js", ".bundle.js", ".chunk.js")
_MINIFIABLE_EXTENSIONS = frozenset({".js", ".mjs", ".cjs", ".css"})

_GENERATED_MARKERS = (
    "generated by",
    "do not edit",
    "@generated",
    "autogenerated",
    "auto-generated",
    "code generated",
)
_GENERATED_HEADER_LINES = 5
_SNIFF_BYTES = 8192
_MINIFIED_SAMPLE_BYTES = 65536
_MINIFIED_AVG_LINE = 300
_MINIFIED_MIN_BYTES = 1000


def classify_dir(name: str, has_child: Callable[[str], bool]) -> SkipReason | None:
    """Decide whether a (non-root) directory is pruned. ``has_child`` checks direct children."""
    if name in _DIR_NAMES:
        return _DIR_NAMES[name]
    if name.endswith(".egg-info"):
        return SkipReason.BUILD_OUTPUT
    if has_child("pyvenv.cfg"):
        return SkipReason.VIRTUALENV
    if has_child(".git"):
        return SkipReason.NESTED_REPOSITORY
    if name in _OUTPUT_DIR_NAMES and not has_child("__init__.py"):
        return SkipReason.BUILD_OUTPUT
    return None


def classify_file(rel_path: str, size: int, max_file_bytes: int) -> SkipReason | None:
    """Name/size-level decision made before a file is read, hashed, or copied."""
    if is_sensitive_path(rel_path):
        return SkipReason.SENSITIVE
    name = PurePosixPath(rel_path).name
    lower = name.lower()
    if name in _BINARY_NAMES or PurePosixPath(lower).suffix in _BINARY_EXTENSIONS:
        return SkipReason.BINARY
    if lower.endswith(_GENERATED_SUFFIXES):
        return SkipReason.GENERATED
    if lower.endswith(_MINIFIED_SUFFIXES):
        return SkipReason.MINIFIED
    if size > max_file_bytes:
        return SkipReason.OVERSIZED
    return None


def _is_migration(rel_path: str) -> bool:
    parts = PurePosixPath(rel_path).parts[:-1]
    return "migrations" in parts or ("alembic" in parts and "versions" in parts)


def classify_content(rel_path: str, data: bytes) -> SkipReason | None:
    """Content-level decision for a file that passed :func:`classify_file`."""
    if b"\x00" in data[:_SNIFF_BYTES]:
        return SkipReason.BINARY
    if not _is_migration(rel_path):
        header = data[:2048].split(b"\n", _GENERATED_HEADER_LINES)[:_GENERATED_HEADER_LINES]
        text = b"\n".join(header).decode("utf-8", errors="replace").lower()
        if any(marker in text for marker in _GENERATED_MARKERS):
            return SkipReason.GENERATED
    if PurePosixPath(rel_path.lower()).suffix in _MINIFIABLE_EXTENSIONS:
        sample = data[:_MINIFIED_SAMPLE_BYTES]
        if len(sample) >= _MINIFIED_MIN_BYTES:
            lines = sample.count(b"\n") + 1
            if len(sample) / lines > _MINIFIED_AVG_LINE:
                return SkipReason.MINIFIED
    return None
