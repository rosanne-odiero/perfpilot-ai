"""Paired A/B benchmark engine.

Baseline and candidate are two source trees of the same workload. For each measured pair, both
variants run in **fresh processes** (``warmups`` untimed calls, then one timed call) in a seeded
random (or alternating) order, on inputs generated by the same fixture with the same seed. Every
process reports a hash of its generated input; the engine refuses to compare when hashes differ.
Memory is measured in separate runs because tracemalloc distorts timing.
"""

from __future__ import annotations

import random
import shutil
import statistics as stdlib_statistics
from collections.abc import Callable
from pathlib import Path
from typing import Any, Literal

from pydantic import BaseModel, Field

from backend.benchmarking.correctness import CorrectnessResult, compare_outputs
from backend.benchmarking.regression_detector import Classification, ClassifierConfig, classify
from backend.benchmarking.statistics import (
    BootstrapCI,
    SampleStats,
    bootstrap_speedup_ci,
    describe,
    latency_reduction_percent,
    speedup,
    throughput,
    throughput_speedup,
)
from backend.models.workloads import InvocationMode, OutputComparison, OutputContract
from backend.profiling.runner import HarnessRun, ResourceLimits, run_harness

VariantName = Literal["baseline", "candidate"]
SampleKind = Literal["preflight", "timing", "memory"]
ProgressFn = Callable[[str, float, str | None], None]
VARIANTS: tuple[VariantName, VariantName] = ("baseline", "candidate")
MEMORY_SAMPLE_INTERVAL_S = 0.005
HIGH_NOISE_CV_PERCENT = 10.0


class BenchmarkPlan(BaseModel):
    entrypoint: str
    fixture: str
    fixture_kwargs: dict[str, Any]
    invocation_mode: InvocationMode
    output_contract: OutputContract
    timeout_seconds: int
    memory_limit_mb: int | None
    permitted_env: list[str] = Field(default_factory=list)
    warmups: int = Field(default=5, ge=0)
    runs: int = Field(default=20, ge=2)
    memory_runs: int = Field(default=3, ge=0)
    seed: int = 0
    order: Literal["random", "alternate"] = "random"
    bootstrap_resamples: int = 10_000
    threshold_percent: float = 5.0


class RawSample(BaseModel):
    variant: VariantName
    kind: SampleKind
    pair_index: int
    position_in_pair: int
    wall_ns: int | None = None
    cpu_ns: int | None = None
    tracemalloc_peak_bytes: int | None = None
    rss_peak_bytes: int | None = None
    ru_maxrss_bytes: int | None = None
    input_sha256: str | None = None
    output_sha256: str | None = None
    ok: bool = True
    error: str | None = None


class VariantSummary(BaseModel):
    wall_ms: SampleStats
    cpu_ms: SampleStats
    throughput_calls_per_s: float


class MemoryVariantSummary(BaseModel):
    runs: int
    tracemalloc_peak_bytes_median: float | None
    rss_peak_bytes_median: float | None
    ru_maxrss_bytes_median: float | None


class PairedBenchmarkResult(BaseModel):
    samples: list[RawSample]
    input_sha256: str | None
    correctness: CorrectnessResult | None
    baseline: VariantSummary | None = None
    candidate: VariantSummary | None = None
    speedup: float | None = None
    cpu_speedup: float | None = None
    latency_reduction_percent: float | None = None
    throughput_speedup: float | None = None
    ci: BootstrapCI | None = None
    classification: Classification
    memory: dict[str, Any] = Field(default_factory=dict)
    warnings: list[str] = Field(default_factory=list)
    failed: bool = False
    error: str | None = None


class _Engine:
    def __init__(
        self,
        plan: BenchmarkPlan,
        roots: dict[VariantName, Path],
        work_dir: Path,
        progress: ProgressFn | None,
    ) -> None:
        self.plan = plan
        self.roots = roots
        self.work_dir = work_dir
        self.progress = progress or (lambda _s, _f, _m: None)
        self.samples: list[RawSample] = []
        self.warnings: list[str] = []
        self.limits = ResourceLimits(
            timeout_seconds=plan.timeout_seconds, memory_limit_mb=plan.memory_limit_mb
        )
        self._counter = 0

    def _run(
        self, variant: VariantName, mode: str, extra: dict[str, Any], rss: float | None
    ) -> HarnessRun:
        self._counter += 1
        run_dir = self.work_dir / f"{self._counter:04d}-{mode}-{variant}"
        request = {
            "mode": mode,
            "workspace_root": str(self.roots[variant]),
            "entrypoint": self.plan.entrypoint,
            "fixture": self.plan.fixture,
            "fixture_kwargs": self.plan.fixture_kwargs,
            "invocation_mode": self.plan.invocation_mode.value,
            **extra,
        }
        try:
            return run_harness(
                request,
                run_dir=run_dir,
                limits=self.limits,
                permitted_env=self.plan.permitted_env,
                rss_sample_interval=rss,
            )
        finally:
            shutil.rmtree(run_dir, ignore_errors=True)

    def _sample(
        self, variant: VariantName, kind: SampleKind, pair: int, position: int, run: HarnessRun
    ) -> RawSample:
        result = run.result or {}
        timing = result.get("timing") or {}
        memory = result.get("memory") or {}
        process = result.get("process") or {}
        sample = RawSample(
            variant=variant,
            kind=kind,
            pair_index=pair,
            position_in_pair=position,
            wall_ns=(timing.get("wall_ns") or [None])[-1],
            cpu_ns=(timing.get("cpu_ns") or [None])[-1],
            tracemalloc_peak_bytes=memory.get("tracemalloc_peak_bytes"),
            rss_peak_bytes=run.rss_peak_bytes,
            ru_maxrss_bytes=process.get("ru_maxrss_bytes"),
            input_sha256=result.get("input_sha256"),
            output_sha256=result.get("output_sha256"),
            ok=run.ok,
            error=None if run.ok else run.failure_reason(),
        )
        self.samples.append(sample)
        return sample

    def _invalid(
        self,
        reason: str,
        correctness: CorrectnessResult | None = None,
        *,
        failed: bool = False,
        input_sha: str | None = None,
    ) -> PairedBenchmarkResult:
        return PairedBenchmarkResult(
            samples=self.samples,
            input_sha256=input_sha,
            correctness=correctness,
            classification=classify(
                speedup=None,
                ci_low=None,
                ci_high=None,
                pairs=0,
                config=ClassifierConfig(threshold_percent=self.plan.threshold_percent),
                invalid_reasons=[reason],
            ),
            warnings=self.warnings,
            failed=failed,
            error=reason if failed else None,
        )

    def _order(self, rng: random.Random, index: int) -> list[VariantName]:
        order = list(VARIANTS)
        if self.plan.order == "alternate":
            return order if index % 2 == 0 else order[::-1]
        rng.shuffle(order)
        return order

    def execute(self) -> PairedBenchmarkResult:
        plan = self.plan
        total_steps = 2 + 2 * plan.runs + 2 * plan.memory_runs
        step = 0

        # 1. Preflight: one call per variant to verify identical inputs and equivalent outputs.
        self.progress("preflight", 0.0, "checking inputs and outputs match")
        preflight: dict[VariantName, dict[str, Any]] = {}
        include_value = plan.output_contract.comparison != OutputComparison.EXACT
        for position, variant in enumerate(VARIANTS):
            run = self._run(
                variant,
                "time",
                {"warmups": 0, "iterations": 1, "include_output_value": include_value},
                None,
            )
            sample = self._sample(variant, "preflight", -1, position, run)
            step += 1
            if not run.ok:
                return self._invalid(f"{variant} preflight run failed: {sample.error}", failed=True)
            preflight[variant] = run.result or {}
        input_sha = preflight["baseline"].get("input_sha256")
        if input_sha != preflight["candidate"].get("input_sha256"):
            return self._invalid(
                "baseline and candidate generated different inputs (input hashes differ); "
                "refusing to compare"
            )
        correctness = compare_outputs(
            preflight["baseline"], preflight["candidate"], plan.output_contract
        )
        if not correctness.equivalent:
            return self._invalid(
                f"candidate output is not equivalent: {correctness.detail}",
                correctness,
                input_sha=input_sha,
            )
        if not preflight["baseline"].get("output_canonical", True):
            self.warnings.append(
                "output contains objects without a canonical form; equality was judged on repr()"
            )

        # 2. Paired timing runs, each in a fresh process.
        rng = random.Random(plan.seed)  # noqa: S311 - reproducible run order, not security
        wall: dict[VariantName, list[int]] = {"baseline": [], "candidate": []}
        cpu: dict[VariantName, list[int]] = {"baseline": [], "candidate": []}
        nondeterministic: set[VariantName] = set()
        mutated: set[VariantName] = set()
        for pair in range(plan.runs):
            for position, variant in enumerate(self._order(rng, pair)):
                run = self._run(variant, "time", {"warmups": plan.warmups, "iterations": 1}, None)
                sample = self._sample(variant, "timing", pair, position, run)
                step += 1
                if not run.ok:
                    return self._invalid(
                        f"{variant} timing run {pair} failed: {sample.error}",
                        correctness,
                        failed=True,
                        input_sha=input_sha,
                    )
                if sample.input_sha256 != input_sha:
                    return self._invalid(
                        f"{variant} run {pair} generated a different input; refusing to compare",
                        correctness,
                        input_sha=input_sha,
                    )
                if sample.output_sha256 != preflight[variant].get("output_sha256"):
                    nondeterministic.add(variant)
                if (run.result or {}).get("input_mutated"):
                    mutated.add(variant)
                assert sample.wall_ns is not None
                assert sample.cpu_ns is not None
                wall[variant].append(sample.wall_ns)
                cpu[variant].append(sample.cpu_ns)
            self.progress("timing", step / total_steps, f"pair {pair + 1}/{plan.runs} measured")
        for name in sorted(nondeterministic):
            self.warnings.append(f"{name} output varied between runs on identical input")
        for name in sorted(mutated):
            self.warnings.append(
                f"{name} mutates its input; warm-up calls changed the data later calls saw"
            )

        # 3. Separate memory runs (tracemalloc + parent-sampled RSS).
        memory_samples: dict[VariantName, list[RawSample]] = {"baseline": [], "candidate": []}
        for index in range(plan.memory_runs):
            order = list(VARIANTS) if index % 2 == 0 else list(VARIANTS)[::-1]
            for position, variant in enumerate(order):
                run = self._run(variant, "memory", {}, MEMORY_SAMPLE_INTERVAL_S)
                sample = self._sample(variant, "memory", index, position, run)
                step += 1
                if not run.ok:
                    self.warnings.append(f"{variant} memory run {index} failed: {sample.error}")
                    continue
                memory_samples[variant].append(sample)
            self.progress("memory", step / total_steps, f"memory run {index + 1} measured")

        return self._summarize(wall, cpu, memory_samples, correctness, input_sha)

    def _summarize(
        self,
        wall: dict[VariantName, list[int]],
        cpu: dict[VariantName, list[int]],
        memory_samples: dict[VariantName, list[RawSample]],
        correctness: CorrectnessResult,
        input_sha: str | None,
    ) -> PairedBenchmarkResult:
        plan = self.plan
        summaries: dict[VariantName, VariantSummary] = {}
        for variant in VARIANTS:
            wall_ms = describe([ns / 1e6 for ns in wall[variant]])
            summaries[variant] = VariantSummary(
                wall_ms=wall_ms,
                cpu_ms=describe([ns / 1e6 for ns in cpu[variant]]),
                throughput_calls_per_s=throughput(1.0, wall_ms.median / 1000.0),
            )
            if wall_ms.cv_percent is not None and wall_ms.cv_percent > HIGH_NOISE_CV_PERCENT:
                self.warnings.append(
                    f"{variant} wall time is noisy (CV {wall_ms.cv_percent:.1f}%); "
                    "consider more runs or a quieter machine"
                )
        if summaries["baseline"].wall_ms.p95_warning:
            self.warnings.append(summaries["baseline"].wall_ms.p95_warning)
        base, cand = summaries["baseline"], summaries["candidate"]
        point = speedup(base.wall_ms.median, cand.wall_ms.median)
        ci = bootstrap_speedup_ci(
            wall["baseline"],
            wall["candidate"],
            resamples=plan.bootstrap_resamples,
            seed=plan.seed,
        )
        classification = classify(
            speedup=point,
            ci_low=ci.low,
            ci_high=ci.high,
            pairs=plan.runs,
            config=ClassifierConfig(threshold_percent=plan.threshold_percent),
        )
        cpu_point: float | None = None
        if base.cpu_ms.median > 0 and cand.cpu_ms.median > 0:
            cpu_point = speedup(base.cpu_ms.median, cand.cpu_ms.median)
        else:
            self.warnings.append(
                "CPU-time speedup unavailable: a median process CPU time was below the OS "
                "process-clock resolution (wall-clock speedup is unaffected)"
            )
        return PairedBenchmarkResult(
            samples=self.samples,
            input_sha256=input_sha,
            correctness=correctness,
            baseline=base,
            candidate=cand,
            speedup=point,
            cpu_speedup=cpu_point,
            latency_reduction_percent=latency_reduction_percent(
                base.wall_ms.median, cand.wall_ms.median
            ),
            throughput_speedup=throughput_speedup(
                cand.throughput_calls_per_s, base.throughput_calls_per_s
            ),
            ci=ci,
            classification=classification,
            memory=_memory_summary(memory_samples),
            warnings=self.warnings,
        )


def _median(values: list[int | None]) -> float | None:
    present = [v for v in values if v is not None]
    return float(stdlib_statistics.median(present)) if present else None


def _memory_summary(samples: dict[VariantName, list[RawSample]]) -> dict[str, Any]:
    per_variant: dict[str, MemoryVariantSummary] = {}
    for variant in VARIANTS:
        rows = samples[variant]
        per_variant[variant] = MemoryVariantSummary(
            runs=len(rows),
            tracemalloc_peak_bytes_median=_median([r.tracemalloc_peak_bytes for r in rows]),
            rss_peak_bytes_median=_median([r.rss_peak_bytes for r in rows]),
            ru_maxrss_bytes_median=_median([r.ru_maxrss_bytes for r in rows]),
        )
    base, cand = per_variant["baseline"], per_variant["candidate"]
    ratio = None
    if base.tracemalloc_peak_bytes_median and cand.tracemalloc_peak_bytes_median is not None:
        ratio = cand.tracemalloc_peak_bytes_median / base.tracemalloc_peak_bytes_median
    return {
        "baseline": base.model_dump(),
        "candidate": cand.model_dump(),
        "tracemalloc_peak_ratio_candidate_to_baseline": ratio,
        "definitions": {
            "tracemalloc_peak_bytes": (
                "peak Python-traced allocations during the workload call only (input built "
                "before tracing); not process memory"
            ),
            "rss_peak_bytes": (
                "peak resident set size of the child process, sampled by the parent every "
                f"{MEMORY_SAMPLE_INTERVAL_S * 1000:g} ms over the whole process lifetime "
                "(interpreter + input + call); short spikes between samples can be missed"
            ),
            "ru_maxrss_bytes": "kernel-reported maximum RSS of the child process (getrusage)",
        },
        "unavailable": [] if base.runs and cand.runs else ["memory runs disabled or failed"],
    }


def run_paired_benchmark(
    plan: BenchmarkPlan,
    *,
    baseline_root: Path,
    candidate_root: Path,
    work_dir: Path,
    progress: ProgressFn | None = None,
) -> PairedBenchmarkResult:
    work_dir.mkdir(parents=True, exist_ok=True)
    roots: dict[VariantName, Path] = {
        "baseline": baseline_root.resolve(),
        "candidate": candidate_root.resolve(),
    }
    try:
        return _Engine(plan, roots, work_dir, progress).execute()
    finally:
        shutil.rmtree(work_dir, ignore_errors=True)
