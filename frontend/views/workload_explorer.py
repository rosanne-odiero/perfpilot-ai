"""Workload explorer: source, input fixture, expected behaviour and the reference comparison."""

from __future__ import annotations

from typing import Any

import pandas as pd
import streamlit as st

from frontend import data
from frontend.api_client import Unsupported
from frontend.components.code_view import render_code
from frontend.components.diff_view import render_side_by_side, unified_diff


def _source(file: dict[str, Any], title: str) -> None:
    note = "truncated" if file.get("truncated") else None
    render_code(
        file["content"], filename=file["path"], title=f"{title} · {file['path']}", note=note
    )


def _expected(spec: dict[str, Any]) -> None:
    expected = spec.get("expected_output") or {}
    if not expected:
        return
    st.markdown("**Expected output contract**")
    st.markdown(
        f"- Type: `{expected.get('type', '?')}`\n"
        f"- Comparison: `{expected.get('comparison', '?')}`"
        + (
            f" (rel_tol {expected.get('rel_tol')}, abs_tol {expected.get('abs_tol')})"
            if expected.get("comparison") == "float_tolerance"
            else ""
        )
        + (f"\n- {expected['description']}" if expected.get("description") else "")
    )


def _sizes(detail: dict[str, Any]) -> None:
    sizes = detail.get("size_parameters") or {}
    if not sizes:
        return
    rows = [
        {"Size": name + (" (default)" if name == detail.get("default_size") else ""), **params}
        for name, params in sizes.items()
    ]
    st.markdown("**Input sizes** (fixture keyword arguments)")
    st.dataframe(pd.DataFrame(rows), hide_index=True, width="stretch")


def _reference(detail: dict[str, Any]) -> None:
    if not detail.get("has_reference_candidate"):
        return
    reference = data.workload_reference(detail["id"])
    if isinstance(reference, Unsupported):
        return
    st.markdown("##### Baseline vs bundled reference implementation")
    st.caption(
        f"The right side is the {reference['label']}: hand-written for tests, not generated by "
        "PerfPilot. Whether it is faster is decided only by the Benchmark tab."
    )
    baseline, ref = reference["baseline"], reference["reference"]
    render_side_by_side(
        baseline["content"],
        ref["content"],
        before_title=f"Baseline · {baseline['path']}",
        after_title=f"Reference · {ref['path']}",
    )
    with st.expander("Unified diff"):
        st.code(
            unified_diff(baseline["content"], ref["content"], baseline["path"], ref["path"])
            or "(identical)",
            language="diff",
        )


def render(detail: dict[str, Any]) -> None:
    left, right = st.columns([1.5, 1], gap="large")
    with left:
        _source(detail["entrypoint_source"], "Entrypoint")
        with st.expander("Input fixture source"):
            _source(detail["fixture_source"], "Fixture")
    with right:
        st.markdown("**Input fixture**")
        st.write(detail.get("fixture_description") or "—")
        _sizes(detail)
        _expected(detail.get("spec") or {})
        if detail.get("suspected_bottleneck"):
            st.markdown("**Suspected bottleneck** (author's note, not measured)")
            st.info(detail["suspected_bottleneck"], icon="🔍")
        if detail.get("readme"):
            with st.expander("README"):
                st.markdown(detail["readme"])
    _reference(detail)
