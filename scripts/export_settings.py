def _type_name(annotation: object) -> str:
    args = typing.get_args(annotation)
    origin = typing.get_origin(annotation)
    if origin is typing.Literal:
        return " \\| ".join(str(a) for a in args)
    if origin is list:
        return "list"
    if args and type(None) in args:
        inner = [a for a in args if a is not type(None)]
        return _type_name(inner[0]) if len(inner) == 1 else "str"
    name = getattr(annotation, "__name__", str(annotation))
    return {"SecretStr": "secret", "Path": "path"}.get(name, name)


def _default(value: object) -> str:
    if value is None:
        return ""
    if isinstance(value, list):
        return f"`{','.join(str(v) for v in value)}`" if value else ""
    if isinstance(value, bool):
        return f"`{str(value).lower()}`"
    return f"`{value}`"


def render_table() -> str:
    from backend.core.config import Settings

    prefix = Settings.model_config.get("env_prefix", "")
    lines = ["| Variable | Type | Default | Description |", "|---|---|---|---|"]
    for name, field in Settings.model_fields.items():
        default = field.get_default(call_default_factory=True)
        lines.append(
            f"| `{prefix}{name.upper()}` | {_type_name(field.annotation)} | {_default(default)} "
            f"| {DESCRIPTIONS.get(name, '')} |"
        )
    return "\n".join(lines)


def updated_document(text: str) -> str:
    head, sep, rest = text.partition(START)
    if not sep or END not in rest:
        raise SystemExit(f"{DEPLOYMENT_MD} is missing the settings-table markers")
    _, _, tail = rest.partition(END)
    return f"{head}{START}\n{render_table()}\n{END}{tail}"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if the table is stale")
    args = parser.parse_args(argv)
    current = DEPLOYMENT_MD.read_text(encoding="utf-8")
    fresh = updated_document(current)
    if fresh == current:
        return 0
    if args.check:
        print("docs/deployment.md settings table is stale — run `make openapi`", file=sys.stderr)
        return 1
    DEPLOYMENT_MD.write_text(fresh, encoding="utf-8")
    print("wrote docs/deployment.md settings table")
    return 0


if __name__ == "__main__":
    sys.exit(main())
