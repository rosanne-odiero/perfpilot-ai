"""Export the API contract: ``docs/openapi.json`` and the endpoint overview ``docs/api.md``.

    python scripts/export_openapi.py          # rewrite both files
    python scripts/export_openapi.py --check  # exit 1 if either file is stale (used by tests/CI)

Both files are generated from the FastAPI app itself, so they cannot drift from the code.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

OPENAPI_PATH = ROOT / "docs" / "openapi.json"
API_MD_PATH = ROOT / "docs" / "api.md"

# Route tags grouped by the workflow they belong to; unknown tags land in "Other".
WORKFLOWS: list[tuple[str, str, list[str]]] = [
    (
        "Repository audit (primary workflow)",
        "Import a repository, run a static audit (never executes code), optionally add AI "
        "recommendations and an approved runtime audit in the sandbox, then export reports.",
        ["repositories", "audits", "recommendations", "runtime", "reports"],
    ),
    (
        "Workload optimization (deep dive)",
        "Profile a workload, generate recommendations and a patch, approve it, validate "
        "correctness and A/B benchmark it.",
        ["workloads", "profiling", "optimization", "benchmarks"],
    ),
    (
        "Platform",
        "Health and the background job queue every long-running endpoint returns.",
        ["health", "jobs"],
    ),
]
METHOD_ORDER = {"get": 0, "post": 1, "put": 2, "patch": 3, "delete": 4}


def build_schema() -> dict[str, Any]:
    from backend.main import create_app

    schema: dict[str, Any] = create_app().openapi()
    return schema


def _ref_name(schema: dict[str, Any] | None) -> str:
    if not schema:
        return ""
    if "$ref" in schema:
        return f"`{schema['$ref'].rsplit('/', 1)[-1]}`"
    if schema.get("type") == "array":
        inner = _ref_name(schema.get("items"))
        return f"list[{inner.strip('`')}]" if inner else "list"
    return schema.get("type", "")


def _returns(op: dict[str, Any]) -> str:
    for code in ("200", "201", "202"):
        response = op.get("responses", {}).get(code)
        if response is None:
            continue
        content = response.get("content", {})
        media = next(iter(content), "")
        body = _ref_name(content.get(media, {}).get("schema")) if media else ""
        if media and media != "application/json":
            body = f"file ({media})" if not body or body == "string" else f"{body} ({media})"
        label = f"{code} {body}".strip()
        return f"{label} — async job" if code == "202" else label
    return ""


def _params(op: dict[str, Any]) -> str:
    names = [f"`{p['name']}`" for p in op.get("parameters", []) if p.get("in") == "query"]
    return ", ".join(names)


def _summary(op: dict[str, Any]) -> str:
    text = (op.get("description") or op.get("summary") or "").strip().splitlines()
    first = text[0] if text else ""
    return first.replace("|", "\\|").replace("``", "`")


def render_markdown(schema: dict[str, Any]) -> str:
    rows: dict[str, list[tuple[str, str, dict[str, Any]]]] = {}
    for path, operations in schema["paths"].items():
        for method, op in operations.items():
            tag = (op.get("tags") or ["other"])[0]
            rows.setdefault(tag, []).append((path, method, op))

    lines = [
        "# PerfPilot API",
        "",
        "<!-- Generated by scripts/export_openapi.py from the FastAPI app. Do not edit by hand;",
        "     run `make openapi` after changing routes. -->",
        "",
        f"Version {schema['info']['version']}. The machine-readable contract is "
        "[`openapi.json`](openapi.json); a running API also serves it at `/openapi.json` with "
        "interactive docs at `/docs`.",
        "",
        "Conventions:",
        "",
        "- All routes are under `/api`. Long-running work returns **202** with a `JobAccepted` "
        "body (`job_id`, `subject_type`, `subject_id`); poll `GET /api/jobs/{job_id}`.",
        '- Errors use one envelope: `{"error": {"code", "message", "details"}}`. Request '
        "validation failures are `422 request_validation_error`.",
        "- Request bodies are capped (`PERFPILOT_MAX_REQUEST_BYTES`, ZIP uploads "
        "`PERFPILOT_MAX_UPLOAD_BYTES`) → `413 limit_exceeded`. List endpoints take bounded "
        "`limit`/`offset` parameters.",
        "- Every result carries a provenance label: `MEASURED`, `STATIC` or `AI_HYPOTHESIS`.",
        "- There is no authentication: the API is meant to listen on localhost only "
        "(see [security.md](security.md)).",
        "",
    ]
    used: set[str] = set()
    sections = [*WORKFLOWS, ("Other", "Routes not yet assigned to a workflow.", sorted(rows))]
    for title, blurb, tags in sections:
        selected = [t for t in tags if t in rows and t not in used]
        if not selected:
            continue
        lines += [f"## {title}", "", blurb, ""]
        for tag in selected:
            used.add(tag)
            lines += [
                f"### {tag}",
                "",
                "| Method | Path | Query | Returns | Summary |",
                "|---|---|---|---|---|",
            ]
            ordered = sorted(rows[tag], key=lambda r: (r[0], METHOD_ORDER.get(r[1], 9)))
            for path, method, op in ordered:
                lines.append(
                    f"| {method.upper()} | `{path}` | {_params(op)} | {_returns(op)} "
                    f"| {_summary(op)} |"
                )
            lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def render_openapi(schema: dict[str, Any]) -> str:
    return json.dumps(schema, indent=2, ensure_ascii=False) + "\n"


def outputs() -> dict[Path, str]:
    schema = build_schema()
    return {OPENAPI_PATH: render_openapi(schema), API_MD_PATH: render_markdown(schema)}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if the files are stale")
    args = parser.parse_args(argv)
    stale = []
    for path, text in outputs().items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == text:
            continue
        if args.check:
            stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(text, encoding="utf-8")
            print(f"wrote {path.relative_to(ROOT)}")
    if stale:
        print(f"stale: {', '.join(stale)} — run `make openapi`", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
